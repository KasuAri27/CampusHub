-- ============================================================================
-- 01 建库
-- ----------------------------------------------------------------------------
-- 全新安装按编号顺序执行（全部要求 MySQL 8.0.19 及以上）：
--   01-create-database.sql  建库（本文件）
--   02-user-tables.sql      账号集群：用户、信用分流水、信用恢复去重、验证码
--   03-task-tables.sql      交易核心：分类字典、需求及五类子表、订单、支付、结算、评价、投诉
--   04-chat-tables.sql      消息集群：会话、会话成员、消息、站内通知
--   05-test-data.sql        仅开发/演示环境：测试账号与各业务状态样例数据，生产库不要执行
--
-- 已有数据的旧库不要重跑 02-04，按 migrations/ 目录下的编号依次升级。
-- 02-04 描述的是“现行完整结构”，修改表结构时须同时更新对应的 02-04 文件
-- 并在 migrations/ 追加一个升级脚本，两者执行后的结构必须一致。
--
-- 约定：
--   * 字符集统一 utf8mb4，排序规则统一 utf8mb4_unicode_ci，每张表显式声明，
--     避免 MySQL 8 默认的 utf8mb4_0900_ai_ci 混入导致跨表比较报错。
--   * 业务时间统一按 Asia/Shanghai 解释；时间列为不带时区的 DATETIME(6)，
--     由应用写入上海时间（JDBC 连接参数 serverTimezone=Asia/Shanghai）。
--   * 记录创建/修改时间的列统一命名 create_time / update_time；
--     其他业务时刻（accepted_at、paid_at 等）保留各自名称。
--   * 索引命名：唯一索引 uk_<表名>_<列名...>，普通索引 idx_<表名>_<列名...>，
--     列名按索引中的顺序用下划线连接；外键依赖的索引也显式命名，不让 MySQL 自动生成。
--   * 布尔值统一 TINYINT(1)，0=否，1=是。
--   * Java 枚举字段对应 MySQL ENUM；Java 字符串字段即使取值固定也用 VARCHAR，
--     取值范围写在列注释中。
-- ============================================================================

CREATE DATABASE IF NOT EXISTS campushub
  DEFAULT CHARACTER SET utf8mb4
  DEFAULT COLLATE utf8mb4_unicode_ci;

USE campushub;
